@pytest.mark.parametrize("label", ("driver present", "reference sheet", "reference audio", "guides three"))
def test_same_path_content_and_unchanged_content(env, tmp_path, label):
    _label, family, build, spec = next(case for case in _all_cases(env, tmp_path) if case[0] == label)
    project, _run = build()
    token, recipe = _identify(env, family, project, spec)
    source = Path(recipe["sources"][-1])
    data = source.read_bytes()
    stat = source.stat()
    # Identical bytes rewritten: a new mtime, the same identity.
    source.write_bytes(data)
    assert _identify(env, family, project, spec)[0] == token
    # Different bytes, same size, the old mtime copied back: a new identity.
    changed = bytearray(data)
    middle = len(changed) // 2
    changed[middle] = (changed[middle] + 1) % 256
    source.write_bytes(bytes(changed))
    os.utime(source, ns=(stat.st_atime_ns, stat.st_mtime_ns))
    assert source.stat().st_size == stat.st_size and source.stat().st_mtime_ns == stat.st_mtime_ns
    assert _identify(env, family, project, spec)[0] != token


