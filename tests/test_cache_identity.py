def test_canonical_recipes_round_trip_exactly(env):
    identity = env.identity
    assert identity.canonical({"b": [1, 2.0, None, "x"], "a": True}) == '{"a":true,"b":[1,2.0,null,"x"]}'
    for bad in ({"a": (1, 2)}, {"a": float("nan")}, {"a": {1: "x"}}, {"a": object()}):
        with pytest.raises(identity.RecipeNotCanonical):
            identity.canonical(bad)


def test_digests_tokens_and_the_run_registry(env, tmp_path, monkeypatch):
    identity, sdk_runs = env.identity, env.sdk_runs
    source = tmp_path / "blob.bin"
    source.write_bytes(os.urandom(3 * identity.CHUNK + 17))
    import hashlib
    assert identity.digest_file(str(source))[0] == hashlib.sha256(source.read_bytes()).hexdigest()
    checks = []
    monkeypatch.setattr(identity, "CHECK_EVERY", 1)
    identity.digest_file(str(source), lambda: checks.append(1))
    assert len(checks) == 4  # an interrupt check between chunks
    with pytest.raises(identity.SourceMissing):
        identity.digest_file(str(tmp_path / "missing.bin"))
    real = identity.stat_snapshot
    calls = iter([[1, 1, 1, 1], [2, 2, 2, 2]])
    monkeypatch.setattr(identity, "stat_snapshot", lambda path: next(calls))
    with pytest.raises(identity.SourceUnstable):
        identity.digest_file(str(source))
    monkeypatch.setattr(identity, "stat_snapshot", real)
    recipe = {"sources": [str(source)], "x": 1}
    first = identity.identify("Kind", recipe)
    assert identity.identify("Kind", recipe)[0] == first[0]
    assert identity.identify("Other", recipe)[0] != first[0]
    assert identity.identify("Kind", {**recipe, "x": 2})[0] != first[0]
    # The registry: bounded, and refused when a prompt id is shared by two open runs.
    monkeypatch.setattr(sdk_runs, "IDENTITY_LIMIT", 1)
    assert sdk_runs.register_identity("k-identity", "p-identity", "t1", "Kind", "{}", {}) == ""
    assert sdk_runs.register_identity("k-identity", "p-identity", "t2", "Kind", "{}", {}) == "registry_full"
    assert sdk_runs.register_identity("k-identity", "p-other", "t3", "Kind", "{}", {}) == "prompt_id_ambiguous"
    sdk_runs.open_release("k-twin", "p-identity", {}, roots=[])
    assert sdk_runs.identity_for("p-identity", "t1") is None
    assert sdk_runs.register_identity("k-identity", "p-identity", "t1", "Kind", "{}", {}) == "prompt_id_ambiguous"
    sdk_runs.close_release("k-twin")
    assert sdk_runs.identity_for("p-identity", "t1") == ("Kind", "{}", {})
    sdk_runs.close_release("k-identity")
    assert sdk_runs.identity_for("p-identity", "t1") is None
