def _cls(m, family):
    return {"driver": m.driver.SonderDriverBridge, "guides": m.guides.SonderGuidesBridgeStart,
            "reference_image": m.reference.SonderReferenceImageBridge,
            "reference_audio": m.reference.SonderReferenceAudioBridge}[family]


def _handle(m, family, project, spec):
    if family == "driver":
        return m.driver.SonderDriverSelector().execute(project, spec["lane"])[0]
    if family == "guides":
        return project
    return m.reference.SonderReferenceSelector.execute(project, "0").args[0]


def _args(family, handle, spec):
    if family == "driver":
        return {"driver_ref": handle}
    if family == "guides":
        return {"project": handle, "bridge_overrides_json": spec["overrides"]}
    return {"reference_set": handle, "unused_slots": spec["unused"]}


def _call(m, family, value, spec):
    """The bridge's own execute, with ``value`` in its token input (a handle, a project or a token)."""
    cls = _cls(m, family)
    if family == "driver":
        return tuple(cls().execute(value))
    if family == "guides":
        out = []
        for index in range(max(1, spec["iterations"])):
            out.extend(cls().execute(value, index, bridge_overrides_json=spec["overrides"])[1:4])
        return tuple(out)
    return tuple(cls.execute(value, spec["unused"]).args)


def _identify(m, family, project, spec, recipe_filter=None):
    """``(token, recipe)`` for the project's current state, as the pipeline would compute it."""
    cls = _cls(m, family)
    recipe = cls.cache_recipe(**_args(family, _handle(m, family, project, spec), spec))
    if recipe_filter is not None:
        recipe = recipe_filter(recipe)
    token, recipe_json, snapshots = m.identity.identify(CLASS[family], recipe)
    assert m.sdk_runs.register_identity("k-identity", "p-identity", token, CLASS[family], recipe_json,
                                        snapshots) == ""
    return token, recipe


