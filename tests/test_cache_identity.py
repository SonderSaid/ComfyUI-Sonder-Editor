"""Media identity (Execution Cache Pipeline Phase 3, M2): the contract every identified bridge keeps.

``nodes/cache_identity.py`` and each ``IDENTIFIES`` class promise:

- the token path decodes exactly what the stock path decodes (and both equal the
  outputs captured before the split, ``tests/test_media_identity_golden.py``);
- **inputs_reach_identity**: any input the stock path reads that changes the
  decoded output changes the token. Generated by perturbing every scalar field
  of the fixture project (scene, clips, assets, References, members, items,
  guides, frozen jobs, the execution context, metadata) and the external-links
  setting; a negative control proves the check can fail;
- **same_path_content**: different bytes at the same path, with the same size
  and a copied modification time, change the token;
- **unchanged_content**: identical bytes rewritten keep it;
- the decoder reads only the recipe and its files: it runs with every project,
  path, setting and colour-probe reader patched to raise;
- ``cache_recipe`` writes nothing and runs no decode (read-only probes only).

Fixtures are real media (``tests/helpers/media_identity_fixtures.py``).
"""

