def _refuse(name):
    def refused(*_args, **_kwargs):
        raise AssertionError(f"the decoder read {name}")
    return refused


def test_the_decoder_reads_only_the_recipe_and_its_files(env, tmp_path, monkeypatch):
    m = env
    work = []
    for label, family, build, spec in _all_cases(m, tmp_path):
        project, _run = build()
        stock = _call(m, family, _handle(m, family, project, spec), spec)
        token, _recipe = _identify(m, family, project, spec)
        work.append((label, family, spec, token, fixtures.digest(stock)))
    path_security = importlib.import_module(f"{PACKAGE}.server.path_security")
    project_storage = importlib.import_module(f"{PACKAGE}.server.project_storage")
    for module in (m.reference_core, m.driver, m.guides, m.media_helpers):
        for name in ("resolve_source_color_interpretation", "_cached_color_probe", "probe_video_color_metadata",
                     "resolve_existing_project_path", "resolve_project_path", "_validated_driver_project_dir",
                     "_filtered_guides", "resolve_reference_set", "_member_records", "hydrate_job",
                     "resolve_driver_ref"):
            if hasattr(module, name):
                monkeypatch.setattr(module, name, _refuse(name))
    for name in ("resolve_existing_project_path", "resolve_project_path", "resolve_under_root", "path_within"):
        monkeypatch.setattr(path_security, name, _refuse(name))
    monkeypatch.setattr(project_storage, "hydrate_job", _refuse("hydrate_job"))
    monkeypatch.setattr(m.external_links, "is_enabled", _refuse("external_links"))
    monkeypatch.setattr(m.external_links, "_read_settings", _refuse("settings"))
    monkeypatch.setattr(m.project_manager, "load_project", _refuse("load_project"))
    for label, family, spec, token, expected in work:
        # The token path receives the recipe back from its canonical JSON, as in a run.
        assert fixtures.digest(_call(m, family, token, spec)) == expected, label


def test_the_decoder_opens_only_the_files_its_recipe_names(env, tmp_path, monkeypatch):
    """A file the decode reads but ``sources`` omits would let its content change unseen:
    every project file a token-path decode opens (ffmpeg and ffprobe argv, OpenCV, open)
    must be in the recipe's sources."""
    import cv2

    m = env
    work = []
    for label, family, build, spec in _all_cases(m, tmp_path):
        project, _run = build()
        token, recipe = _identify(m, family, project, spec)
        work.append((label, family, spec, token, {os.path.normcase(path) for path in recipe["sources"]}))
    root = os.path.normcase(str(tmp_path))
    opened: set[str] = set()

    def note(path):
        try:
            text = os.path.normcase(os.path.abspath(os.fspath(path)))
        except TypeError:
            return
        if text.startswith(root) and os.path.isfile(text):
            opened.add(text)

    real_popen, real_imread, real_capture, real_open = subprocess.Popen, cv2.imread, cv2.VideoCapture, open

    class Popen(real_popen):
        def __init__(self, args, *a, **k):
            for item in args if isinstance(args, (list, tuple)) else [args]:
                if isinstance(item, (str, os.PathLike)):
                    note(item)
            super().__init__(args, *a, **k)

    monkeypatch.setattr(subprocess, "Popen", Popen)
    monkeypatch.setattr(cv2, "imread", lambda path, *a, **k: (note(path), real_imread(path, *a, **k))[1])
    monkeypatch.setattr(cv2, "VideoCapture", lambda path, *a, **k: (note(path), real_capture(path, *a, **k))[1])
    monkeypatch.setattr("builtins.open", lambda file, *a, **k: (note(file), real_open(file, *a, **k))[1])
    checked = 0
    for label, family, spec, token, sources in work:
        opened.clear()
        _call(m, family, token, spec)
        assert opened <= sources, (label, sorted(opened - sources))
        checked += bool(opened)
    assert checked >= 10  # most cases really open media


# --- cache_recipe writes nothing and decodes nothing --------------------------------------------------


def test_cache_recipe_writes_nothing_and_runs_only_read_only_probes(env, tmp_path, monkeypatch):
    m = env
    builds = []
    for label, family, build, spec in _all_cases(m, tmp_path):
        project, _run = build()
        builds.append((label, family, spec, project, _handle(m, family, project, spec)))
    real_popen = subprocess.Popen
    probes = []

    class ReadOnlyProbe(real_popen):
        def __init__(self, args, *a, **k):
            exe = os.path.basename(str(args[0])).lower() if isinstance(args, (list, tuple)) else ""
            text = [str(item) for item in args] if isinstance(args, (list, tuple)) else [str(args)]
            decoding = any(flag in text for flag in ("rawvideo", "f32le", "s16le")) or "-y" in text
            if not (exe.startswith("ffprobe") or exe.startswith("ffmpeg")) or decoding:
                raise AssertionError(f"cache_recipe ran {text[:6]}")
            probes.append(exe)
            super().__init__(args, *a, **k)

    real_open = open

    def guarded_open(file, mode="r", *args, **kwargs):
        if any(flag in str(mode) for flag in "wax+"):
            raise AssertionError(f"cache_recipe opened {file!r} for writing")
        return real_open(file, mode, *args, **kwargs)

    monkeypatch.setattr(subprocess, "Popen", ReadOnlyProbe)
    monkeypatch.setattr("builtins.open", guarded_open)
    for name in ("replace", "rename", "remove", "unlink", "makedirs", "mkdir"):
        monkeypatch.setattr(os, name, _refuse(f"os.{name}"))
    state = {name: repr(value) for name, value in vars(m.sdk_runs).items()
             if not name.startswith("__") and isinstance(value, (dict, list, set))}
    for label, family, spec, project, handle in builds:
        before = copy.deepcopy(getattr(project, "_execution_context", {}))
        recipe = _cls(m, family).cache_recipe(**_args(family, handle, spec))
        m.identity.canonical(recipe)
        assert getattr(project, "_execution_context", {}) == before, label
    after = {name: repr(value) for name, value in vars(m.sdk_runs).items()
             if not name.startswith("__") and isinstance(value, (dict, list, set))}
    assert after == state


def test_the_colour_heuristic_size_probe_is_cached_by_file_signature(env, tmp_path, monkeypatch):
    # A Driver recipe is built every prompt; an untagged clip must not cost an ffprobe each time.
    media = env.media_helpers
    calls = []
    monkeypatch.setattr(media, "probe_video_size", lambda path: calls.append(path) or (640, 360))
    clip = tmp_path / "clip.mkv"
    clip.write_bytes(b"x" * 10)
    assert media._cached_heuristic_size(str(clip)) == (640, 360)
    assert media._cached_heuristic_size(str(clip)) == (640, 360)
    assert len(calls) == 1
    clip.write_bytes(b"x" * 11)  # a changed file is probed again
    media._cached_heuristic_size(str(clip))
    assert len(calls) == 2
    media._cached_heuristic_size(str(tmp_path / "missing.mkv"))  # unreadable: never cached
    media._cached_heuristic_size(str(tmp_path / "missing.mkv"))
    assert len(calls) == 4


